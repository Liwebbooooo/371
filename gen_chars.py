def build_char_data(char_list, grade_name, level):
    """为一组字构建数据"""
    result = []
    for item in char_list:
        ch = item["char"]
        py = get_pinyin(ch)
        strokes = get_strokes(ch)
        result.append({
            "char": ch,
            "pinyin": py,
            "strokes": strokes,
            "words": item.get("words", [f"暂无组词"]),
            "sentence": item.get("sentence", f"这是一个包含「{ch}」字的句子。"),
            "grade": grade_name,
            "level": level
        })
    return result

