def get_strokes(char):
    """获取笔画数"""
    return STROKE_MAP.get(char, 8)  # 默认为8画

def get_pinyin(char):
    """获取拼音"""
    try:
        result = pinyin(char, style=Style.TONE)
        if result and result[0]:
            return result[0][0]
    except:
        pass
    return ''

