# 从CJK基本区(U+4E00~U+9FFF)获取大量常用汉字
# 加上常见的扩展字
def get_common_chars():
    chars = []
    # CJK Unified Ideographs - 基本区
    for cp in range(0x4E00, 0x9FC0):
        ch = chr(cp)
        chars.append(ch)
    return chars

COMMON_CHARS_LIST = get_common_chars()

# 次常用1000字不再需要，使用CJK范围生成
# 空列表占位
LESS_COMMON = ""

def is_chinese(ch):
    return '\u4e00' <= ch <= '\u9fff'

